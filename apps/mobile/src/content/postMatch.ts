export function pickPostMatchLine(
  myScore: number,
  theirScore: number,
  seed = Date.now(),
  demo = false,
): PostMatchLine {
  const tone: PostMatchTone = demo
    ? 'demo'
    : myScore > theirScore
      ? 'win'
      : myScore < theirScore
        ? 'lose'
        : 'draw';
  const pool = postMatchLinesRu.filter((l) => l.tone === tone);
  const idx = Math.abs(seed) % pool.length;
  return pool[idx] ?? pool[0];
}
